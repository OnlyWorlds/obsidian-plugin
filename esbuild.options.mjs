import { builtinModules } from "node:module";

const banner =
`/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

/**
 * The plugin's esbuild options, one copy: the build (esbuild.config.mjs) and
 * the test build (test/support/build-for-tests.mjs, whose bundle the
 * bundle-load test requires) both read them. One CJS `main.js`, the only
 * shape Obsidian loads; @onlyworlds/sdk 4.x is ESM only and is bundled into
 * it (3.10).
 */
export function pluginBuildOptions(prod, outfile = "main.js") {
	return {
		banner: {
			js: banner,
		},
		entryPoints: ["main.ts"],
		bundle: true,
		external: [
			"obsidian",
			"electron",
			"@codemirror/autocomplete",
			"@codemirror/collab",
			"@codemirror/commands",
			"@codemirror/language",
			"@codemirror/lint",
			"@codemirror/search",
			"@codemirror/state",
			"@codemirror/view",
			"@lezer/common",
			"@lezer/highlight",
			"@lezer/lr",
			...builtinModules],
		format: "cjs",
		target: "es2018",
		logLevel: "info",
		sourcemap: prod ? false : "inline",
		treeShaking: true,
		outfile,
		minify: prod,
	};
}
